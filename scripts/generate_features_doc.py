"""Generates docs/modelling/features.md from the real
`feature_definitions` table -- per Phase 3 §11's file list, this
document is marked "(generated)": it is a direct rendering of what the
database actually holds, not hand-typed, so it can never drift from
the real feature catalog."""

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from sqlalchemy import text  # noqa: E402

from ledgerlight.config.settings import load_settings  # noqa: E402
from ledgerlight.db.session import make_session_factory  # noqa: E402

OUTPUT_PATH = REPO_ROOT / "docs" / "modelling" / "features.md"


def main() -> int:
    settings = load_settings()
    session_factory = make_session_factory(settings)

    with session_factory() as session:
        version_rows: list[str] = list(
            session.execute(text("SELECT DISTINCT version FROM feature_definitions")).scalars()
        )
        versions: list[str] = sorted(set(version_rows))

        lines = [
            "# Feature Catalog (generated)",
            "",
            "Generated by `scripts/generate_features_doc.py` from the real",
            "`feature_definitions` table -- never hand-edited; re-run the script to",
            "refresh after any feature-build change.",
            "",
        ]

        for version in versions:
            rows = session.execute(
                text(
                    "SELECT name, provenance_tier, track, lookback_days, description, "
                    "as_of_semantics FROM feature_definitions WHERE version = :v ORDER BY name"
                ),
                {"v": version},
            ).all()
            snapshot_count = session.execute(
                text("SELECT count(*) FROM feature_snapshots WHERE feature_set_version = :v"),
                {"v": version},
            ).scalar()
            distinct_companies = session.execute(
                text(
                    "SELECT count(DISTINCT company_id) FROM feature_snapshots "
                    "WHERE feature_set_version = :v"
                ),
                {"v": version},
            ).scalar()

            lines.append(f"## `{version}`")
            lines.append("")
            lines.append(
                f"Real built `feature_snapshots` rows: **{snapshot_count}**, "
                f"across **{distinct_companies}** distinct companies."
            )
            lines.append("")
            lines.append("| Feature | Tier | Track | Lookback (days) | Description |")
            lines.append("|---|---|---|---|---|")
            for name, tier, track, lookback_days, description, _as_of_semantics in rows:
                lookback_str = str(lookback_days) if lookback_days is not None else "n/a"
                lines.append(f"| `{name}` | {tier} | {track} | {lookback_str} | {description} |")
            lines.append("")
            if rows:
                lines.append(f"**as_of semantics:** {rows[0][5]}")
                lines.append("")

    OUTPUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUTPUT_PATH} ({len(versions)} feature_set_version groups)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
