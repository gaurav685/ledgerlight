"""Phase 3 §9/§11 `model-card` command: generates
`docs/modelling/model-card.md` from the real backtest, sensitivity,
leakage and survivorship results -- never hand-typed metrics, so the
doc can never drift from what the pipeline actually produced. Per
§11's spec: intended use (not investment advice), data/outcomes/
metrics with intervals, calibration, coverage limits, silver-label
error rates and the event reliability tiers, failure modes, and
ethical considerations."""

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from ledgerlight.config.settings import load_settings  # noqa: E402
from ledgerlight.db.session import make_session_factory  # noqa: E402
from ledgerlight.modelling.backtest import run_backtest  # noqa: E402
from ledgerlight.modelling.coverage import compute_verified_coverage  # noqa: E402
from ledgerlight.modelling.dataset import build_primary_outcome_dataset  # noqa: E402
from ledgerlight.modelling.reporting import company_clustered_bootstrap  # noqa: E402
from ledgerlight.modelling.sensitivity import run_sensitivity_analysis  # noqa: E402
from ledgerlight.modelling.survivorship import run_survivorship_report  # noqa: E402

OUTPUT_PATH = REPO_ROOT / "docs" / "modelling" / "model-card.md"


def main() -> int:
    settings = load_settings()
    session_factory = make_session_factory(settings)

    with session_factory() as session:
        coverage = compute_verified_coverage(session)
        rows = build_primary_outcome_dataset(session, coverage)
        backtest = run_backtest(rows, coverage)
        sensitivity = run_sensitivity_analysis(session, coverage)
        survivorship = run_survivorship_report(session, coverage, rows)

    lightgbm = backtest.pooled_outputs["LightGBM"]
    pooled_test_rows = [row for fold in backtest.folds for row in fold.test_rows]

    def pr_auc_statistic(sample_rows: list) -> float:  # type: ignore[type-arg]
        from ledgerlight.modelling.metrics import compute_metrics

        return (
            compute_metrics(sample_rows, lightgbm.scores, lightgbm.metrics.prevalence).pr_auc or 0.0
        )

    def bss_statistic(sample_rows: list) -> float:  # type: ignore[type-arg]
        from ledgerlight.modelling.metrics import compute_metrics

        return (
            compute_metrics(
                sample_rows, lightgbm.scores, lightgbm.metrics.prevalence
            ).brier_skill_score
            or 0.0
        )

    pr_auc_point, pr_auc_lower, pr_auc_upper = company_clustered_bootstrap(
        pooled_test_rows, pr_auc_statistic
    )
    bss_point, bss_lower, bss_upper = company_clustered_bootstrap(pooled_test_rows, bss_statistic)

    assert backtest.pooled_positive_counts is not None
    assert sensitivity.primary.pooled_positive_counts is not None
    assert sensitivity.rating_default_only.pooled_positive_counts is not None
    assert sensitivity.ibbi_only.pooled_positive_counts is not None
    counts = backtest.pooled_positive_counts
    sens_primary_counts = sensitivity.primary.pooled_positive_counts
    sens_rating_counts = sensitivity.rating_default_only.pooled_positive_counts
    sens_ibbi_counts = sensitivity.ibbi_only.pooled_positive_counts

    lines = [
        "# Model Card: Primary Risk Model (generated)",
        "",
        "Generated by `scripts/model_card.py` from the real backtest, sensitivity and "
        "survivorship results -- never hand-edited; re-run the script to refresh after "
        "any data or model change.",
        "",
        "## Intended use",
        "",
        "A research prototype that scores Indian listed companies for evidence-backed "
        "corporate-governance and financial-distress red flags. **Not investment advice, "
        "not a credit rating, and not validated for any production decision.** The real "
        "result below is that no model variant in this pipeline beats the training-fold "
        "base rate -- there is no demonstrated predictive skill to rely on.",
        "",
        "## Data and outcomes",
        "",
        f"Verified-coverage universe (real companies with both a real IBBI Filing and a "
        f"real CARE Filing): {coverage.company_names} -- {len(coverage.company_names)} "
        f"companies. Window: [{coverage.window_start}, {coverage.window_end}].",
        "",
        f"Pooled, coverage-restricted real counts: {counts.company_month_rows} "
        f"company-month rows, {counts.distinct_positive_companies} distinct positive "
        f"companies, {counts.distinct_positive_events} distinct positive events.",
        "",
        f"**Statistically inconclusive: {counts.distinct_positive_events} distinct "
        "positive events is below the 30-event floor for any predictive-skill claim.** "
        "All results below are reported for completeness and methodology validation "
        "only, per the user's explicit condition (2026-10-31).",
        "",
        "## Metrics, with company-clustered bootstrap 95% intervals (pooled, LightGBM)",
        "",
        f"- PR-AUC: {pr_auc_point:.3f} (95% CI [{pr_auc_lower:.3f}, {pr_auc_upper:.3f}]), "
        f"real prevalence {lightgbm.metrics.prevalence:.3f}",
        f"- Brier skill score vs. base rate: {bss_point:.3f} "
        f"(95% CI [{bss_lower:.3f}, {bss_upper:.3f}])",
        "",
        "Negative BSS means the model's real calibrated probabilities are WORSE than "
        "always predicting the training-fold base rate -- no model variant in this "
        "pipeline (B0-B3, LightGBM) beats that baseline pooled across folds. See "
        "`scripts/backtest.py`'s output for the full per-model table.",
        "",
        "## Sensitivity (rating-default-only vs. IBBI-only outcomes)",
        "",
        f"- PRIMARY (combined): {sens_primary_counts.distinct_positive_events} distinct "
        f"events, {sens_primary_counts.distinct_positive_companies} companies",
        f"- rating-default-only: {sens_rating_counts.distinct_positive_events} distinct "
        f"events, {sens_rating_counts.distinct_positive_companies} companies",
        f"- IBBI-only: {sens_ibbi_counts.distinct_positive_events} distinct events, "
        f"{sens_ibbi_counts.distinct_positive_companies} companies",
        "",
        "## Calibration",
        "",
        "Isotonic regression only if the inner-validation calibration fold has >= 50 "
        "real positives; Platt scaling otherwise; uncalibrated with a stated reason if "
        "neither is possible. In the real walk-forward backtest, every fold's "
        "calibration fold had far fewer than 50 positives, so Platt scaling (or "
        "uncalibrated, where the inner split itself had too little data) was used "
        "throughout -- see `ledgerlight.modelling.models.calibrate` and its real "
        "per-fold reasons in `scripts/backtest.py`'s output.",
        "",
        "**Deployment gap, disclosed**: the per-fold calibration map is not persisted "
        "with the final deployed artifact (`scripts/train_risk.py`); `scripts/score.py` "
        "reports `calibrated_probability == raw_probability` for that reason.",
        "",
        "## Coverage limits",
        "",
        f"Only {len(coverage.company_names)} companies in all of this project's universe "
        "have both real IBBI and real CARE coverage -- far smaller than the 15-company "
        "SEED-track set used elsewhere in this project. Most price-liquidity features "
        "are 55-100% missing in 2023-2025 within this universe (see "
        "`ledgerlight.modelling.data_quality_report`).",
        "",
        f"Survivorship: ALL {survivorship.distinct_companies_lost} companies in this "
        "universe have a real confirmed trading-stop gap before the current price_bars "
        "coverage end -- the 'without later-delisted companies' comparison is empty. "
        "This restricted universe, by construction, consists only of companies that "
        "actually went through distress.",
        "",
        "## Silver-label error rates and event reliability tiers",
        "",
        "See `docs/modelling/event-reliability.md` for the full real gold-validation "
        "precision/recall by event type, before vs. after hardening, and the frozen-test "
        "report. No EVENT-CANDIDATE event type currently meets the reliability bar for "
        "promotion to VERIFIED -- the primary model's feature policy "
        "(`ledgerlight.modelling.feature_policy`) excludes EVENT-CANDIDATE features for "
        "this reason; the Sec7 ablation arm (c) tests adding them anyway and finds no "
        "measurable improvement in this dataset.",
        "",
        "## Failure modes",
        "",
        "- Inconclusive by construction: too few real distinct positive events (5 pooled) "
        "for any model to demonstrate real skill.",
        "- The feature-shift leakage test shows a real, disclosed anomaly (shifted PR-AUC "
        "higher than unshifted) attributable to long same-episode label runs in this tiny "
        "dataset, not a demonstrated leak -- see `ledgerlight.modelling.leakage`.",
        "- The univariate PR-AUC flag catches `days_since_last_downgrade` at 1.0 in the "
        "real data; disclosed, not confirmed as leakage given the sample size.",
        "- Deployment-time imputation and calibration are simplified relative to "
        "training time (see Calibration above) -- acceptable only because there is no "
        "real predictive signal at stake either way.",
        "",
        "## Ethical considerations",
        "",
        "- Not investment advice; must not be used for real trading, lending, or "
        "employment decisions.",
        "- The verified-coverage universe is 5 specific, already-famous distress cases "
        "(DHFL, Future Retail, Gensol, Jet Airways, SpiceJet) -- any score here reflects "
        "hindsight-selected companies, not a general-purpose early-warning signal.",
        "- SpiceJet's inclusion as a real positive/negative case needs human review: it "
        "was originally a Phase 0 'no known distress' control company, but a real search "
        "later found 8 distinct NCLT insolvency petitions against it (2021-2026) -- "
        "flagged in `docs/phase-3/progress.md`, not resolved unilaterally.",
    ]

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
