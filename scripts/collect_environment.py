"""Capture real tool/OS versions and write docs/phase-0/environment-report.md.

Phase 0 ground rule: versions must come from actually running commands, never
be typed by hand. This script is that single source of truth; re-run it any
time the report needs refreshing.
"""

from __future__ import annotations

import datetime as dt
import platform
import shutil
import subprocess
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
REPORT_PATH = REPO_ROOT / "docs" / "phase-0" / "environment-report.md"

# Candidate source homepages for a single, polite reachability GET.
# (Full terms/robots.txt research lives in docs/data/source-inventory.md —
# this is only a basic up/down check, as required by Phase 0 §1.)
CANDIDATE_SOURCES = {
    "BSE": "https://www.bseindia.com",
    "NSE": "https://www.nseindia.com",
    "SEBI": "https://www.sebi.gov.in",
    "IBBI": "https://www.ibbi.gov.in",
    "CRISIL Ratings": "https://www.crisilratings.com",
    "ICRA": "https://www.icra.in",
    "CARE Ratings": "https://www.careratings.com",
    "India Ratings": "https://www.indiaratings.co.in",
    "Acuite": "https://www.acuite.in",
    "Infomerics": "https://www.infomerics.com",
    "Brickwork Ratings": "https://www.brickworkratings.com",
    "MCA": "https://www.mca.gov.in",
}

USER_AGENT = "LedgerlightPhase0Research/0.1 (contact: gaurav685@gmail.com)"


def run(cmd: list[str], timeout: int = 15) -> str:
    """Run cmd, return combined stdout+stderr stripped, or a not-found marker."""
    exe = shutil.which(cmd[0])
    if exe is None:
        return "NOT FOUND on PATH"
    try:
        proc = subprocess.run(
            [exe, *cmd[1:]],
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
        out = (proc.stdout or "") + (proc.stderr or "")
        return out.strip() or f"(exit {proc.returncode}, no output)"
    except Exception as exc:  # noqa: BLE001 - this is a diagnostic probe
        return f"ERROR: {exc!r}"


def uv_python_312() -> str:
    uv = shutil.which("uv")
    if uv is None:
        return "uv NOT FOUND on PATH"
    out = run(["uv", "python", "find", "3.12"])
    return out


def reachability() -> dict[str, str]:
    import urllib.error
    import urllib.request

    results: dict[str, str] = {}
    for name, url in CANDIDATE_SOURCES.items():
        req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT}, method="GET")
        try:
            with urllib.request.urlopen(req, timeout=10) as resp:  # noqa: S310
                results[name] = f"HTTP {resp.status}"
        except urllib.error.HTTPError as exc:
            results[name] = f"HTTP {exc.code}"
        except Exception as exc:  # noqa: BLE001
            results[name] = f"UNREACHABLE ({exc.__class__.__name__})"
    return results


def disk_free_gb(path: Path) -> str:
    usage = shutil.disk_usage(path)
    return f"{usage.free / (1024**3):.1f} GiB free of {usage.total / (1024**3):.1f} GiB total"


def nvidia_smi() -> str:
    exe = shutil.which("nvidia-smi")
    if exe is None:
        return "not present (no NVIDIA GPU driver detected) — informational only, not required"
    out = run(
        ["nvidia-smi", "--query-gpu=name,driver_version,memory.total", "--format=csv,noheader"]
    )
    return out


def main() -> None:
    now = dt.datetime.now(dt.UTC).isoformat()

    rows = {
        "git --version": run(["git", "--version"]),
        "python3 --version": run(["python3", "--version"]),
        "python3.12 --version (on PATH)": run(["python3.12", "--version"]),
        "python3.12 via uv-managed toolchain": uv_python_312(),
        "uv --version": run(["uv", "--version"]),
        "node -v": run(["node", "-v"]),
        "pnpm -v": run(["pnpm", "-v"]),
        "npm -v": run(["npm", "-v"]),
        "docker version (client)": run(["docker", "version"]),
        "docker compose version": run(["docker", "compose", "version"]),
        "tesseract --version": run(["tesseract", "--version"]),
        "pdftoppm -v": run(["pdftoppm", "-v"]),
    }

    uname = f"{platform.system()} {platform.release()} ({platform.version()}) {platform.machine()}"
    reach = reachability()

    lines: list[str] = []
    lines.append("# Phase 0 Environment Report")
    lines.append("")
    lines.append(f"Generated by `scripts/collect_environment.py` at {now}.")
    lines.append("Every value below came from actually running the named command on this machine.")
    lines.append("")
    lines.append("## OS / platform")
    lines.append("")
    lines.append(f"- `platform.platform()`: {uname}")
    lines.append(
        "- Shell used for acquisition/dev commands: Git Bash (MINGW64) on Windows; "
        "PowerShell also available"
    )
    lines.append(f"- Disk ({REPO_ROOT.drive or REPO_ROOT.anchor}): {disk_free_gb(REPO_ROOT)}")
    lines.append(
        f"- nvidia-smi: {nvidia_smi()} (informational only — Phase 0 uses no GPU libraries)"
    )
    lines.append("")
    lines.append("## Tool versions")
    lines.append("")
    lines.append("| Command | Output |")
    lines.append("|---|---|")
    for cmd, out in rows.items():
        out_oneline = out.replace("\n", " / ")
        lines.append(f"| `{cmd}` | `{out_oneline}` |")
    lines.append("")
    lines.append(
        "Notes: `python3.12` and `uv` were not present as pre-existing system installs; "
        "`uv` was installed user-scoped via `pip install --user uv`, and Python 3.12.15 was "
        "then fetched into uv's own managed toolchain directory via `uv python install 3.12` "
        "(not a system-wide Python install). See docs/adr/0001-technology-stack.md."
    )
    lines.append("")
    lines.append("## Candidate data-source reachability (single GET, not crawling)")
    lines.append("")
    lines.append("| Source | URL | Result |")
    lines.append("|---|---|---|")
    for name, url in CANDIDATE_SOURCES.items():
        lines.append(f"| {name} | {url} | {reach[name]} |")
    lines.append("")
    lines.append(
        "This is a basic reachability probe only. Full robots.txt / terms-of-use / access-method "
        "findings are in `docs/data/source-inventory.md`."
    )
    lines.append("")

    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {REPORT_PATH}")


if __name__ == "__main__":
    main()
