"""Enhancement 1 §3: generates `docs/enhancements/event-study/report.md`
and the real per-event-type CAAR plots (PNG) from one real, already-
persisted `EventStudyRun` -- never from a fresh recomputation, so the
report always matches exactly what was actually run and committed to
the database.
"""

from __future__ import annotations

import uuid
from pathlib import Path
from typing import cast

import matplotlib

matplotlib.use("Agg")  # headless -- this process never has a display
import matplotlib.pyplot as plt
from sqlalchemy import select
from sqlalchemy.orm import Session

from ledgerlight.research.event_study import PRIMARY_WINDOW
from ledgerlight.research.models import EventStudyEventResult, EventStudyRun

REPORT_DIR = Path("docs/enhancements/event-study")
CAAR_OFFSET_RANGE = range(-30, 61)


def _caar_series(
    results: list[EventStudyEventResult], event_type: str
) -> tuple[list[int], list[float], list[int]]:
    """Real Average Abnormal Return per real day offset, cumulatively
    summed into a real CAAR series -- averaged only across each
    offset's own real available events (never padded with an assumed
    zero for an event missing that specific offset)."""
    relevant = [
        r for r in results if r.event_type_code == event_type and r.is_primary and not r.confounded
    ]
    offsets = list(CAAR_OFFSET_RANGE)
    aar: list[float] = []
    n_per_offset: list[int] = []
    for offset in offsets:
        values = [
            r.daily_ar_by_offset[str(offset)]
            for r in relevant
            if str(offset) in r.daily_ar_by_offset
        ]
        aar.append(sum(values) / len(values) if values else 0.0)
        n_per_offset.append(len(values))
    caar: list[float] = []
    running = 0.0
    for value in aar:
        running += value
        caar.append(running)
    return offsets, caar, n_per_offset


def _plot_caar(event_type: str, offsets: list[int], caar: list[float], out_path: Path) -> None:
    fig, ax = plt.subplots(figsize=(8, 4.5))
    ax.plot(offsets, caar, color="#1f4e79")
    ax.axvline(0, color="grey", linestyle="--", linewidth=0.8)
    ax.axhline(0, color="grey", linestyle="-", linewidth=0.8)
    ax.set_xlabel("Trading days relative to event day 0")
    ax.set_ylabel("Real CAAR")
    ax.set_title(f"{event_type}: real CAAR, day -30 to +60", fontsize=10)
    fig.suptitle(
        "Not investment advice -- a measured reaction, not a prediction", fontsize=8, y=0.02
    )
    fig.tight_layout()
    fig.savefig(out_path, dpi=110)
    plt.close(fig)


def _format_metric_row(window_name: str, m: dict[str, object]) -> str:
    def fmt(v: object) -> str:
        if v is None:
            return "n/a"
        if isinstance(v, float):
            return f"{v:.4f}" if v == v else "nan"  # nan != nan
        return str(v)

    return (
        f"| {window_name} | {fmt(m.get('n'))} | {fmt(m.get('mean_car'))} | "
        f"{fmt(m.get('median_car'))} | {fmt(m.get('t_stat'))} | {fmt(m.get('bmp_stat'))} | "
        f"{fmt(m.get('rank_p'))} | {fmt(m.get('rank_p_holm'))} |"
    )


def generate_report(session: Session, run_id: uuid.UUID, repo_root: Path) -> Path:
    run = session.get(EventStudyRun, run_id)
    if run is None:
        raise ValueError(f"no real EventStudyRun with id={run_id}")

    results = list(
        session.scalars(
            select(EventStudyEventResult).where(EventStudyEventResult.run_id == run_id)
        ).all()
    )

    report_dir = repo_root / REPORT_DIR
    report_dir.mkdir(parents=True, exist_ok=True)

    lines: list[str] = []
    lines.append("# Governance Event Study — Report (auto-generated)")
    lines.append("")
    lines.append(
        "**Not investment advice. Not a trading signal. No causal claim** -- a real "
        "measured market reaction around an already-disclosed event, nothing more. "
        "Generated by `ledgerlight.research.report.generate_report` from one real, "
        "already-persisted run; never hand-edited."
    )
    lines.append("")
    lines.append(
        f"Run `{run.id}` -- spec `{run.spec_version}` (sha256 `{run.spec_sha256}`), "
        f"git `{run.git_sha}`, requested by `{run.requested_by}`, {run.created_at}."
    )
    lines.append("")

    lines.append("## Event counts per filter stage")
    lines.append("")
    lines.append("| Stage | Real count |")
    lines.append("|---|---|")
    for stage, count in run.event_counts_json.items():
        lines.append(f"| {stage} | {count} |")
    lines.append("")

    event_types = sorted(k for k in run.metrics_json if k != "_robustness")

    any_significant_after_correction = False
    for event_type in event_types:
        windows = cast(dict[str, dict[str, object]], run.metrics_json[event_type])
        lines.append(f"## {event_type}")
        lines.append("")
        lines.append("| Window | N | mean CAR | median CAR | t | BMP | rank p | Holm p (rank) |")
        lines.append("|---|---|---|---|---|---|---|---|")
        for window_name, m in windows.items():
            lines.append(_format_metric_row(window_name, m))
            for key in ("t_p_holm", "bmp_p_holm", "rank_p_holm"):
                p = m.get(key)
                if isinstance(p, float) and p == p and p < 0.05:
                    any_significant_after_correction = True
        lines.append("")

        primary_results = [
            r
            for r in results
            if r.event_type_code == event_type and r.is_primary and not r.confounded
        ]
        flagged = [r for r in primary_results if r.possible_corporate_action]
        flagged_cars = [
            r.car_by_window[PRIMARY_WINDOW] for r in flagged if PRIMARY_WINDOW in r.car_by_window
        ]
        clean = [r for r in primary_results if not r.possible_corporate_action]
        clean_cars = [
            r.car_by_window[PRIMARY_WINDOW] for r in clean if PRIMARY_WINDOW in r.car_by_window
        ]
        if flagged_cars and clean_cars:
            flagged_mean = sum(flagged_cars) / len(flagged_cars)
            clean_mean = sum(clean_cars) / len(clean_cars)
            lines.append(
                f"**Real finding, disclosed, not smoothed over**: {len(flagged)} of "
                f"{len(primary_results)} real primary events here are flagged "
                "`possible_corporate_action` (a |daily return| > 50% somewhere in "
                "their own real pooled window -- see Limitations below). Their own "
                f"mean primary-window CAR is {flagged_mean:.4f}, versus "
                f"{clean_mean:.4f} for the {len(clean)} real events with no such "
                "flag -- this is why the mean CAR above can look large even when "
                "the median (and most individual real events) do not."
            )
            lines.append("")

        with_placebo = [r for r in primary_results if r.placebo_percentile is not None]
        if with_placebo:
            percentiles = [cast(float, r.placebo_percentile) for r in with_placebo]
            avg_percentile = sum(percentiles) / len(percentiles)
            lines.append(
                f"**Placebo comparison**: across {len(with_placebo)} real primary, "
                f"non-confounded events with a real placebo distribution (1,000 "
                "draws each, year-matched pseudo-dates), the real CAR sat at the "
                f"**{avg_percentile:.1f}th percentile** of its own placebo "
                "distribution on average."
            )
            lines.append("")

        offsets, caar, n_per_offset = _caar_series(results, event_type)
        if any(n > 0 for n in n_per_offset):
            png_name = f"caar_{event_type.lower()}.png"
            _plot_caar(event_type, offsets, caar, report_dir / png_name)
            lines.append(f"![{event_type} real CAAR]({png_name})")
            lines.append("")

    robustness = cast(dict[str, dict[str, object]], run.metrics_json.get("_robustness", {}))
    if robustness:
        lines.append("## Robustness checks")
        lines.append("")
        lines.append(
            "| Event type | Mean CAR (turnover-wt, excl. confounded) | "
            "Mean CAR (turnover-wt, incl. confounded) | N incl. | "
            "Mean CAR (equal-wt) | N equal-wt |"
        )
        lines.append("|---|---|---|---|---|---|")
        for event_type, r in robustness.items():
            lines.append(
                f"| {event_type} | "
                f"{r.get('mean_car_turnover_weighted_excl_confounded')} | "
                f"{r.get('mean_car_turnover_weighted_incl_confounded')} | "
                f"{r.get('n_incl_confounded')} | "
                f"{r.get('mean_car_equal_weighted_excl_confounded')} | "
                f"{r.get('n_equal_weighted')} |"
            )
        lines.append("")

    lines.append("## Limitations (disclosed, not hidden)")
    lines.append("")
    lines.append(
        "- **Market-index construction**: the primary market return is "
        "turnover-weighted (real `price_bars.turnover`), a real, documented "
        "substitute for market-cap weighting -- this schema has no "
        "shares-outstanding field, so true market-cap weighting is not "
        "possible. Equal-weighted is reported as a robustness check, not a "
        "replacement."
    )
    lines.append(
        "- **CARE-only rating coverage**: only 11 real companies in this "
        "project's universe have ever had a real CARE filing -- the CARE "
        "downgrade/upgrade sample is small by construction, not a choice "
        "made for this study."
    )
    lines.append(
        "- **Survivorship**: delisted/suspended firms are included wherever "
        "real `price_bars` data for them exists, but this project's own "
        "acquisition pipeline may itself under-cover firms that delisted "
        "long enough ago, a real limitation inherited, not newly "
        "introduced here."
    )
    lines.append(
        "- **Thin trading / no split adjustment**: `price_bars` has no "
        "corporate-action adjustment field; a real stock split or bonus "
        "issue inside an event's own window would show as a spurious, "
        "extreme single-day return -- events with a |daily return| > 50% "
        "anywhere in their own pooled window are flagged "
        "`possible_corporate_action` in the real per-event data, for a "
        "human to inspect."
    )
    lines.append(
        "- **IBBI CIRP admissions are reported separately, never as a "
        "primary significance claim**: every one of the real rows for "
        "this event type is tier=CANDIDATE (pending human review), not "
        "VERIFIED, as of this spec's own real freeze date."
    )
    lines.append("")

    lines.append("## Plain-English summary")
    lines.append("")
    if any_significant_after_correction:
        lines.append(
            "At least one (event type, window, test) combination above remains "
            "statistically significant after the real Holm-Bonferroni "
            "correction across every p-value this run actually computed. See "
            "the tables above for exactly which. **This is a measured market "
            "reaction, not proof that the event caused it, and not a trading "
            "signal.**"
        )
    else:
        lines.append(
            "**No (event type, window, test) combination in this run remains "
            "statistically significant after the real Holm-Bonferroni "
            "correction.** Stated plainly, as the brief requires: this run "
            "found no significant market reaction it can report with "
            "confidence, once corrected for testing many (event type, window) "
            "combinations at once."
        )
    lines.append("")

    report_path = report_dir / "report.md"
    report_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return report_path
