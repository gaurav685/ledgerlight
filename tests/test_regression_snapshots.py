"""Phase 6A §4: golden-snapshot regression tests over a fixed real
subset of this project's own already-persisted production data --
never synthetic, never re-generated by this test itself. Covers
extraction outputs, event sets/tiers, entity links, feature values at
a fixed as_of, score values for a frozen model artifact, and a dossier
hash from the offline renderer.

The golden values live in tests/fixtures/regression_snapshots.json.
Any real, intentional change to the underlying pipeline that changes
one of these values must be reflected there via
`scripts/update_regression_snapshots.py --confirm` (never a hand
edit) -- see that script's own docstring and
docs/phase-6/evidence/sec04-regression-snapshots.md for the documented
history of what changed and why.

A failure here means one of two things: a real regression (the
pipeline now produces a different answer for the same frozen real
input), or a deliberate, intentional change that was never reflected
in the golden file -- the test cannot tell the two apart, which is the
point: a human decides which one happened.
"""

from __future__ import annotations

import hashlib
import json
import uuid
from collections.abc import Iterator
from pathlib import Path
from typing import Any

import pytest
from sqlalchemy import text
from sqlalchemy.orm import Session

from ledgerlight.agent.export import export_dossier_markdown
from ledgerlight.agent.models import Dossier, Investigation
from ledgerlight.config.settings import Settings
from ledgerlight.db.session import make_session_factory
from ledgerlight.knowledge.models import Company

pytestmark = pytest.mark.integration

GOLDEN_PATH = Path(__file__).resolve().parent / "fixtures" / "regression_snapshots.json"


@pytest.fixture(scope="module")
def golden() -> dict[str, Any]:
    data: dict[str, Any] = json.loads(GOLDEN_PATH.read_text(encoding="utf-8"))
    return data


@pytest.fixture(scope="module")
def real_session() -> Iterator[Session]:
    repo_root = Path(__file__).resolve().parent.parent
    try:
        settings = Settings(_env_file=str(repo_root / ".env"))  # type: ignore[call-arg]
    except Exception as exc:
        pytest.skip(f"could not load real .env for integration test: {exc}")
    try:
        session = make_session_factory(settings)()
    except Exception as exc:
        pytest.skip(f"Postgres not reachable (is the Docker stack up?): {exc}")
    yield session
    session.close()


def test_extraction_outputs_match_golden(real_session: Session, golden: dict[str, Any]) -> None:
    expected = golden["extraction"]
    rows = real_session.execute(
        text(
            "SELECT ef.value_json, ef.validation_status, e.status, e.severity, "
            "e.detector_name, e.detector_version "
            "FROM event_fields ef JOIN events e ON e.id = ef.event_id "
            "WHERE e.company_id = :cid AND ef.field_name = :field "
            "ORDER BY ef.value_json, e.detector_version, ef.id"
        ),
        {"cid": expected["company_id"], "field": expected["field_name"]},
    ).fetchall()
    actual = sorted(
        (
            {
                "value_json": r[0],
                "validation_status": r[1],
                "event_status": r[2],
                "event_severity": r[3],
                "detector_name": r[4],
                "detector_version": r[5],
            }
            for r in rows
        ),
        key=lambda d: json.dumps(d, sort_keys=True),
    )
    expected_records = sorted(expected["records"], key=lambda d: json.dumps(d, sort_keys=True))
    assert len(actual) == len(expected_records), (
        f"expected {len(expected_records)} real audit_firm event_fields for "
        f"{expected['company_name']}, found {len(actual)} -- a real extraction "
        f"regression, or a deliberate change not yet reflected in the golden file"
    )
    assert actual == expected_records


def test_events_and_tiers_match_golden(real_session: Session, golden: dict[str, Any]) -> None:
    expected = golden["events_and_tiers"]
    rows = real_session.execute(
        text(
            "SELECT et.code, e.status, e.severity, count(*) "
            "FROM events e JOIN event_types et ON et.id = e.event_type_id "
            "WHERE e.company_id = :cid "
            "GROUP BY et.code, e.status, e.severity ORDER BY et.code, e.status, e.severity"
        ),
        {"cid": expected["company_id"]},
    ).fetchall()
    actual = [
        {"event_type_code": r[0], "status": r[1], "severity": r[2], "count": r[3]} for r in rows
    ]
    assert actual == expected["by_type_status_severity"], (
        f"real event tier distribution for {expected['company_name']} changed -- "
        "a real regression, or an undocumented golden-snapshot update"
    )


def test_entity_links_match_golden(real_session: Session, golden: dict[str, Any]) -> None:
    expected = golden["entity_links"]
    rows = real_session.execute(
        text(
            "SELECT method, score, status FROM entity_links "
            "WHERE entity_id = :eid ORDER BY method, score"
        ),
        {"eid": expected["entity_id"]},
    ).fetchall()
    actual = sorted(
        ({"method": r[0], "score": r[1], "status": r[2]} for r in rows),
        key=lambda d: json.dumps(d, sort_keys=True),
    )
    expected_records = sorted(expected["records"], key=lambda d: json.dumps(d, sort_keys=True))
    assert actual == expected_records, (
        f"real entity_links for {expected['entity_display_name']!r} changed -- "
        "a real entity-resolution regression, or an undocumented golden-snapshot update"
    )


def test_feature_values_match_golden(real_session: Session, golden: dict[str, Any]) -> None:
    expected = golden["feature_values"]
    rows = real_session.execute(
        text(
            "SELECT feature_set_version, values FROM feature_snapshots "
            "WHERE company_id = :cid AND as_of = :as_of"
        ),
        {"cid": expected["company_id"], "as_of": expected["as_of"]},
    ).fetchall()
    actual = {r[0]: r[1] for r in rows}
    expected_by_version = expected["by_feature_set_version"]
    assert set(actual) == set(expected_by_version), (
        f"real feature_set_version coverage for {expected['company_name']} at "
        f"{expected['as_of']} changed -- a real regression, or an undocumented "
        "golden-snapshot update"
    )
    for version, expected_values in expected_by_version.items():
        assert actual[version] == expected_values, (
            f"real feature values for {expected['company_name']} at {expected['as_of']} "
            f"({version}) changed -- a real features-build regression, or an "
            "undocumented golden-snapshot update"
        )


def test_score_matches_golden(real_session: Session, golden: dict[str, Any]) -> None:
    expected = golden["score"]
    row = real_session.execute(
        text(
            "SELECT calibrated_probability, raw_probability, percentile, outcome_spec_hash "
            "FROM scores WHERE company_id = :cid AND as_of = :as_of "
            "AND model_name = :model_name AND model_version = :model_version"
        ),
        {
            "cid": expected["company_id"],
            "as_of": expected["as_of"],
            "model_name": expected["model_name"],
            "model_version": expected["model_version"],
        },
    ).first()
    assert row is not None, (
        f"no real score found for {expected['company_name']} at {expected['as_of']} "
        f"for {expected['model_name']} v{expected['model_version']} -- was it deleted, "
        "or was the frozen model artifact replaced without updating this golden file?"
    )
    assert row[0] == expected["calibrated_probability"]
    assert row[1] == expected["raw_probability"]
    assert row[2] == expected["percentile"]
    assert row[3] == expected["outcome_spec_hash"], (
        "the real outcome_spec_hash this score was trained against changed -- "
        "this score is no longer reproducible against the frozen spec this golden "
        "file recorded; re-run backtest reproducibility (§5) before updating this file"
    )


def test_dossier_hash_matches_golden(real_session: Session, golden: dict[str, Any]) -> None:
    expected = golden["dossier"]
    investigation = real_session.get(Investigation, uuid.UUID(expected["investigation_id"]))
    dossier = real_session.get(Dossier, uuid.UUID(expected["dossier_id"]))
    assert investigation is not None and dossier is not None, (
        "the real frozen investigation/dossier this golden snapshot points at no "
        "longer exists -- investigate before re-pointing this golden file at a "
        "different one"
    )
    company = real_session.get(Company, investigation.company_id)
    company_name = company.display_name if company is not None else str(investigation.company_id)
    markdown = export_dossier_markdown(dossier, investigation, company_name)
    actual_hash = hashlib.sha256(markdown.encode()).hexdigest()
    assert actual_hash == expected["markdown_sha256"], (
        f"the offline-rendered Markdown for {expected['company_name']}'s real, "
        "frozen dossier changed byte-for-byte -- a real renderer regression (or a "
        "real, underlying data change to a row this golden snapshot assumed was "
        "frozen), or an undocumented golden-snapshot update"
    )
